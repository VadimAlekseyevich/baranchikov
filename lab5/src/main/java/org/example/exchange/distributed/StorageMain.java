package org.example.exchange.distributed;

import org.example.exchange.wire.ExchangeWire.Packet;

import java.net.ServerSocket;
import java.net.Socket;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Executors;

/** Layer 3: SQL persistence only. No matching decisions and no knowledge of UDP. */
public final class StorageMain {
    private static final int PORT = Integer.parseInt(Wire.env("STORAGE_PORT", "9102"));
    private static final String URL = Wire.env("H2_URL", "jdbc:h2:tcp://database:9092/exchange;WRITE_DELAY=0;LOCK_TIMEOUT=30000");

    private StorageMain() { }

    public static void main(String[] args) throws Exception {
        Exception last = null;
        boolean ready = false;
        for (int attempt = 0; attempt < 60; attempt++) {
            try (Connection connection = openDatabase()) {
                initialize(connection);
                ready = true;
                break;
            } catch (Exception e) {
                last = e;
                Thread.sleep(500);
            }
        }
        if (!ready) throw new IllegalStateException("Database failed to become ready", last);
        System.out.println("Protobuf storage layer on TCP " + PORT);
        try (ServerSocket server = new ServerSocket(PORT);
             var workers = Executors.newCachedThreadPool()) {
            while (true) {
                Socket socket = server.accept();
                workers.submit(() -> handle(socket));
            }
        }
    }

    private static Connection openDatabase() throws Exception {
        return DriverManager.getConnection(URL, "sa", "");
    }

    static void initialize(Connection c) throws Exception {
        try (Statement s = c.createStatement()) {
            s.executeUpdate("CREATE TABLE IF NOT EXISTS tx_guard (id INT PRIMARY KEY)");
            s.executeUpdate("MERGE INTO tx_guard (id) KEY (id) VALUES (1)");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS exchange_orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id VARCHAR(255) NOT NULL, base_currency VARCHAR(32) NOT NULL, quote_currency VARCHAR(32) NOT NULL, side VARCHAR(4) NOT NULL, limit_price DECIMAL(38, 18) NOT NULL, original_quantity DECIMAL(38, 18) NOT NULL, remaining_quantity DECIMAL(38, 18) NOT NULL)");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS trades (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, base_currency VARCHAR(32) NOT NULL, quote_currency VARCHAR(32) NOT NULL, price DECIMAL(38, 18) NOT NULL, quantity DECIMAL(38, 18) NOT NULL, buy_order_id BIGINT NOT NULL, sell_order_id BIGINT NOT NULL, buyer_id VARCHAR(255) NOT NULL, seller_id VARCHAR(255) NOT NULL)");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS pending_notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id VARCHAR(255) NOT NULL, trade_id BIGINT NOT NULL, CONSTRAINT fk_pending_trade FOREIGN KEY(trade_id) REFERENCES trades(id))");
        }
    }

    private static void handle(Socket socket) {
        try (socket; Connection c = openDatabase()) {
            c.setAutoCommit(false);
            boolean transaction = false;
            Packet request;
            while ((request = Packet.parseDelimitedFrom(socket.getInputStream())) != null) {
                Packet response;
                try {
                    switch (request.getOp()) {
                        case "BEGIN" -> {
                            if (transaction) throw new IllegalStateException("Transaction already begun");
                            // A single H2 row serializes modifications across ALL storage replicas.
                            try (PreparedStatement ps = c.prepareStatement("SELECT id FROM tx_guard WHERE id=1 FOR UPDATE")) {
                                try (ResultSet rs = ps.executeQuery()) {
                                    if (!rs.next()) throw new IllegalStateException("Missing transaction guard");
                                }
                            }
                            transaction = true;
                            response = Wire.packet("OK").build();
                        }
                        case "COMMIT" -> {
                            if (!transaction) throw new IllegalStateException("No active transaction");
                            c.commit();
                            transaction = false;
                            response = Wire.packet("OK").build();
                        }
                        case "ROLLBACK" -> {
                            c.rollback();
                            transaction = false;
                            response = Wire.packet("OK").build();
                        }
                        default -> {
                            if (requiresTransaction(request.getOp()) && !transaction)
                                throw new IllegalStateException("Write operation requires BEGIN");
                            response = process(c, request);
                        }
                    }
                } catch (Exception e) {
                    c.rollback();
                    transaction = false;
                    response = Wire.error(e);
                }
                response.writeDelimitedTo(socket.getOutputStream());
                socket.getOutputStream().flush();
            }
            // Disconnected clients must not accidentally commit unfinished work.
            c.rollback();
        } catch (Exception e) {
            System.err.println("Storage connection closed: " + e.getMessage());
        }
    }

    private static boolean requiresTransaction(String op) {
        return switch (op) {
            case "INSERT_ORDER", "FIND_MATCH", "UPDATE_REMAINING", "INSERT_TRADE", "SAVE_NOTIFICATION", "TAKE_NOTIFICATIONS" -> true;
            default -> false;
        };
    }

    static Packet process(Connection c, Packet p) throws Exception {
        return switch (p.getOp()) {
            case "INSERT_ORDER" -> insertOrder(c, p);
            case "FIND_MATCH" -> findMatch(c, p);
            case "UPDATE_REMAINING" -> updateRemaining(c, p);
            case "INSERT_TRADE" -> insertTrade(c, p);
            case "SAVE_NOTIFICATION" -> saveNotification(c, p);
            case "OPEN_ORDERS" -> openOrders(c, p);
            case "TRADES" -> trades(c);
            case "TAKE_NOTIFICATIONS" -> takeNotifications(c, p);
            default -> throw new IllegalArgumentException("Unknown storage operation: " + p.getOp());
        };
    }

    private static Packet insertOrder(Connection c, Packet p) throws Exception {
        String sql = "INSERT INTO exchange_orders(client_id,base_currency,quote_currency,side,limit_price,original_quantity,remaining_quantity) VALUES(?,?,?,?,?,?,?)";
        try (PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, p.getClientId());
            ps.setString(2, p.getBase());
            ps.setString(3, p.getQuote());
            ps.setString(4, p.getSide());
            ps.setBigDecimal(5, new java.math.BigDecimal(p.getPrice()));
            ps.setBigDecimal(6, new java.math.BigDecimal(p.getQuantity()));
            ps.setBigDecimal(7, new java.math.BigDecimal(p.getQuantity()));
            ps.executeUpdate();
            return Wire.packet("OK").setOrderId(generatedId(ps)).build();
        }
    }

    private static Packet findMatch(Connection c, Packet p) throws Exception {
        String opposite = p.getSide().equals("BUY") ? "SELL" : "BUY";
        String comparison = p.getSide().equals("BUY") ? "<=" : ">=";
        String sql = "SELECT id,client_id,limit_price,remaining_quantity FROM exchange_orders " +
                "WHERE base_currency=? AND quote_currency=? AND side=? AND remaining_quantity>0 " +
                "AND limit_price " + comparison + " ? ORDER BY id FETCH FIRST 1 ROW ONLY";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, p.getBase());
            ps.setString(2, p.getQuote());
            ps.setString(3, opposite);
            ps.setBigDecimal(4, new java.math.BigDecimal(p.getPrice()));
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) return Wire.packet("MATCH").setFound(false).build();
                return Wire.packet("MATCH").setFound(true).setOrderId(rs.getLong("id"))
                        .setClientId(rs.getString("client_id"))
                        .setPrice(rs.getBigDecimal("limit_price").toPlainString())
                        .setRemaining(rs.getBigDecimal("remaining_quantity").toPlainString()).build();
            }
        }
    }

    private static Packet updateRemaining(Connection c, Packet p) throws Exception {
        try (PreparedStatement ps = c.prepareStatement("UPDATE exchange_orders SET remaining_quantity=? WHERE id=?")) {
            ps.setBigDecimal(1, new java.math.BigDecimal(p.getRemaining()));
            ps.setLong(2, p.getOrderId());
            if (ps.executeUpdate() != 1) throw new IllegalArgumentException("Unknown order ID");
            return Wire.packet("OK").build();
        }
    }

    private static Packet insertTrade(Connection c, Packet p) throws Exception {
        String sql = "INSERT INTO trades(base_currency,quote_currency,price,quantity,buy_order_id,sell_order_id,buyer_id,seller_id) VALUES(?,?,?,?,?,?,?,?)";
        try (PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, p.getBase());
            ps.setString(2, p.getQuote());
            ps.setBigDecimal(3, new java.math.BigDecimal(p.getPrice()));
            ps.setBigDecimal(4, new java.math.BigDecimal(p.getQuantity()));
            ps.setLong(5, p.getBuyOrderId());
            ps.setLong(6, p.getSellOrderId());
            ps.setString(7, p.getBuyerId());
            ps.setString(8, p.getSellerId());
            ps.executeUpdate();
            return Wire.packet("OK").setTradeId(generatedId(ps)).build();
        }
    }

    private static Packet saveNotification(Connection c, Packet p) throws Exception {
        try (PreparedStatement ps = c.prepareStatement("INSERT INTO pending_notifications(client_id,trade_id) VALUES(?,?)")) {
            ps.setString(1, p.getClientId());
            ps.setLong(2, p.getTradeId());
            ps.executeUpdate();
            return Wire.packet("OK").build();
        }
    }

    private static Packet openOrders(Connection c, Packet p) throws Exception {
        String sql = "SELECT * FROM exchange_orders WHERE base_currency=? AND quote_currency=? AND remaining_quantity>0 ORDER BY id";
        Packet.Builder reply = Wire.packet("OPEN_ORDERS");
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, p.getBase());
            ps.setString(2, p.getQuote());
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    reply.addItems(Wire.packet("ORDER").setOrderId(rs.getLong("id"))
                            .setClientId(rs.getString("client_id"))
                            .setBase(rs.getString("base_currency"))
                            .setQuote(rs.getString("quote_currency"))
                            .setSide(rs.getString("side"))
                            .setPrice(rs.getBigDecimal("limit_price").toPlainString())
                            .setQuantity(rs.getBigDecimal("original_quantity").toPlainString())
                            .setRemaining(rs.getBigDecimal("remaining_quantity").toPlainString()));
                }
            }
        }
        return reply.build();
    }

    private static Packet.Builder tradeFields(ResultSet rs) throws Exception {
        return Wire.packet("TRADE").setTradeId(rs.getLong("id"))
                .setBase(rs.getString("base_currency"))
                .setQuote(rs.getString("quote_currency"))
                .setPrice(rs.getBigDecimal("price").toPlainString())
                .setQuantity(rs.getBigDecimal("quantity").toPlainString())
                .setBuyOrderId(rs.getLong("buy_order_id"))
                .setSellOrderId(rs.getLong("sell_order_id"))
                .setBuyerId(rs.getString("buyer_id"))
                .setSellerId(rs.getString("seller_id"));
    }

    private static Packet trades(Connection c) throws Exception {
        Packet.Builder reply = Wire.packet("TRADES");
        try (Statement ps = c.createStatement(); ResultSet rs = ps.executeQuery("SELECT * FROM trades ORDER BY id")) {
            while (rs.next()) reply.addItems(tradeFields(rs));
        }
        return reply.build();
    }

    private static Packet takeNotifications(Connection c, Packet p) throws Exception {
        String sql = "SELECT n.id AS notification_id, t.* FROM pending_notifications n JOIN trades t ON t.id=n.trade_id WHERE n.client_id=? ORDER BY n.id";
        Packet.Builder reply = Wire.packet("EVENTS");
        List<Long> ids = new ArrayList<>();
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, p.getClientId());
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    ids.add(rs.getLong("notification_id"));
                    reply.addItems(Wire.packet("EVENT").setClientId(p.getClientId())
                            .setNotificationId(rs.getLong("notification_id"))
                            .addItems(tradeFields(rs)));
                }
            }
        }
        try (PreparedStatement ps = c.prepareStatement("DELETE FROM pending_notifications WHERE id=?")) {
            for (long id : ids) {
                ps.setLong(1, id);
                ps.addBatch();
            }
            ps.executeBatch();
        }
        return reply.build();
    }

    private static long generatedId(PreparedStatement ps) throws Exception {
        try (ResultSet rs = ps.getGeneratedKeys()) {
            if (!rs.next()) throw new IllegalStateException("No generated ID");
            return rs.getLong(1);
        }
    }
}
